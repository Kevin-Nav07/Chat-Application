const { HttpError } = require("../helpers/ErrorExtensions");

// Service class responsible for persisting and retrieving messages from the PostgreSQL database
class MessageService {
    #_dbClient; // database client instance provided by the service context pool

    // Constructor assigns the active database client connection
    constructor(connection) {
        this.#_dbClient = connection; // stores active database client for executing queries
    }

    // Persists a new message to the database and returns the full message payload with sender information
    async saveMessageAsync(roomId, userId, content, messageType = 'text') {
        // Validates that required parameters are provided
        if (roomId == null || userId == null || !content) {
            throw new HttpError(400, "Room ID, User ID, and message content are required"); // rejects empty payloads
        }

        // Trims content and checks character limits according to the message protocol specification
        const trimmedContent = content.trim(); // removes surrounding whitespace
        if (trimmedContent.length < 1 || trimmedContent.length > 4000) {
            throw new HttpError(400, "Message content must be between 1 and 4000 characters"); // enforces length boundary
        }

        // Verifies that the sender is actually an enrolled member of the specified room
        const membershipCheck = await this.#_dbClient.query(
            "SELECT 1 FROM room_members WHERE room_id = $1 AND user_id = $2",
            [roomId, userId]
        ); // queries membership table for matching room and user

        if (membershipCheck.rows.length === 0) {
            throw new HttpError(403, "You are not a member of this room"); // rejects unauthorized sender
        }

        try {
            // Begins database transaction to guarantee data integrity
            await this.#_dbClient.query("BEGIN"); // starts SQL transaction block

            // Inserts the message and immediately joins with users to retrieve the sender's public username
            const insertQuery = `
                WITH inserted AS (
                    INSERT INTO messages (room_id, user_id, content, message_type)
                    VALUES ($1, $2, $3, $4)
                    RETURNING id, room_id, user_id, content, message_type, created_at
                )
                SELECT
                    inserted.id,
                    inserted.room_id,
                    inserted.user_id AS sender_id,
                    users.username AS sender_username,
                    inserted.content,
                    inserted.message_type,
                    inserted.created_at
                FROM inserted
                JOIN users ON users.id = inserted.user_id;
            `; // CTE executes insertion and joins sender details in a single round trip

            const result = await this.#_dbClient.query(insertQuery, [
                roomId,
                userId,
                trimmedContent,
                messageType,
            ]); // executes parameterized query to prevent SQL injection

            await this.#_dbClient.query("COMMIT"); // commits transaction to persist record permanently

            const row = result.rows[0]; // extracts the single created record
            return {
                id: row.id, // primary key generated by postgres
                room_id: row.room_id, // unique identifier of the target room
                sender_id: row.sender_id, // user id of the person who sent the message
                sender_username: row.sender_username, // display username of the author
                content: row.content, // the message text
                message_type: row.message_type, // text or system message type
                created_at: row.created_at, // timestamp when row was written to disk
            };
        } catch (error) {
            await this.#_dbClient.query("ROLLBACK"); // cancels transaction if any error occurs
            console.error("Error saving message to database:", error); // logs failure for debugging
            throw error; // rethrows error for controller or websocket handler
        }
    }

    // Retrieves paginated message history for a specific room, ordered newest first
    async getRoomMessagesAsync(roomId, userId, cursorId, cursorCreatedAt, limit = 30) {
        // Enforces membership check before revealing room message history
        const membershipCheck = await this.#_dbClient.query(
            "SELECT 1 FROM room_members WHERE room_id = $1 AND user_id = $2",
            [roomId, userId]
        ); // confirms requestor belongs to the conversation

        if (membershipCheck.rows.length === 0) {
            throw new HttpError(403, "You are not a member of this room"); // forbids non-members from reading messages
        }

        // Restricts page limit between 1 and 100 messages
        const parsedLimit = Math.min(Math.max(parseInt(limit, 10) || 30, 1), 100); // clamps pagination limit safely

        try {
            let result;
            if (cursorId == null || cursorCreatedAt == null) {
                // Initial page fetch without an active cursor
                const query = `
                    SELECT
                        messages.id,
                        messages.room_id,
                        messages.user_id AS sender_id,
                        users.username AS sender_username,
                        messages.content,
                        messages.message_type,
                        messages.created_at,
                        messages.created_at::text AS cursor_created_at
                    FROM messages
                    JOIN users ON users.id = messages.user_id
                    WHERE messages.room_id = $1
                    ORDER BY messages.created_at DESC, messages.id DESC
                    LIMIT $2;
                `; // orders newest first so initial fetch grabs the latest conversations
                result = await this.#_dbClient.query(query, [roomId, parsedLimit]); // executes query
            } else {
                // Subsequent page fetch using compound cursor comparison (created_at, id)
                const query = `
                    SELECT
                        messages.id,
                        messages.room_id,
                        messages.user_id AS sender_id,
                        users.username AS sender_username,
                        messages.content,
                        messages.message_type,
                        messages.created_at,
                        messages.created_at::text AS cursor_created_at
                    FROM messages
                    JOIN users ON users.id = messages.user_id
                    WHERE messages.room_id = $1 AND (messages.created_at, messages.id) < ($2::timestamptz, $3)
                    ORDER BY messages.created_at DESC, messages.id DESC
                    LIMIT $4;
                `; // compound cursor avoids missing messages sharing identical millisecond timestamps
                result = await this.#_dbClient.query(query, [
                    roomId,
                    cursorCreatedAt,
                    cursorId,
                    parsedLimit,
                ]); // executes cursor query
            }

            return result.rows; // returns list of message records
        } catch (error) {
            console.error("Error retrieving room messages from database:", error); // logs query failure
            throw error; // rethrows error for caller
        }
    }
}

module.exports = MessageService;

